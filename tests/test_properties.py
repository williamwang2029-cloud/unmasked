FAST = settings(max_examples=30, deadline=None)


# ---------------------------------------------------------------------------
# 3.2 Token determinism and round trip
# ---------------------------------------------------------------------------
@FAST
@given(value=st.text(min_size=0, max_size=40))
def test_token_determinism_and_roundtrip(value):
    # Use a throwaway keys dir so real keys/ is never touched; restore afterwards.
    import tempfile
    saved = tokens_mod.KEYS_DIR
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="pbt_keys_"))
    try:
        ensure_keys(str(tmp))  # sets KEYS_DIR = tmp and creates vault.key/join.key there
        # Determinism: same value -> same token, twice.
        assert join_token(value) == join_token(value)
        df = pd.DataFrame({"row_id": [0], "x": [value]})
        vault = str(tmp / "vault_x.csv")
        out = tokenize_column(df, "x", vault_path=vault)
        # Reversibility: detokenize returns the original string value.
        assert detokenize(out["x"].iloc[0], "x", vault_path=vault) == str(value)
    finally:
        tokens_mod.KEYS_DIR = saved


# ---------------------------------------------------------------------------
# 2.5 Suppression completeness
# ---------------------------------------------------------------------------
_YEARS = [2014, 2016, 2018, 2020, 2022, 2024]
_CLASSES = ["FY", "SR", "Other"]
_AFF = ["Ring-tailed lemur", "Indri", "Aye-aye", "Golden bamboo lemur",
        "Crowned lemur", "Diademed sifaka", "Gray mouse lemur"]


@FAST
@given(
    n=st.integers(min_value=30, max_value=120),
    k=st.integers(min_value=2, max_value=6),
    seed=st.integers(min_value=0, max_value=10_000),
)
def test_suppression_completeness(n, k, seed):
    rng = np.random.default_rng(seed)
    df = pd.DataFrame({
        "row_id": np.arange(n),
        "Year": rng.choice(_YEARS, size=n),
        "Class": rng.choice(_CLASSES, size=n),
        "affiliation": rng.choice(_AFF, size=n),
    })
    qis = ["Year", "Class", "affiliation"]
    res = greedy_generalize(df, qis, k=k, max_suppression=0.05, group_col="affiliation")
    rel, active = res["release_df"], res["active_qis"]
    if not active or len(rel) == 0:
        return  # vacuously satisfied: nothing identifying remains
    sizes = rel.groupby(active, dropna=False)[active[0]].transform("size")
    assert int(sizes.min()) >= k, f"class smaller than k={k}: min={int(sizes.min())}"


# ---------------------------------------------------------------------------
# 2.4 Lockstep derived drop
# ---------------------------------------------------------------------------
@FAST
@given(n=st.integers(min_value=5, max_value=40), seed=st.integers(0, 10_000))
def test_lockstep_derived_drop(n, seed):
    rng = np.random.default_rng(seed)
    df = pd.DataFrame({
        "row_id": np.arange(n),
        "MAJfirstcode": rng.integers(1001, 1011, size=n),
        "MAJfirstcol": rng.integers(21, 33, size=n),
        "MAJfirst": [f"Field {i%5}: Track {i%3}" for i in range(n)],
    })
    # MAJfirstcode level 2 is "drop"; derived MAJfirst/MAJfirstcol must drop in lockstep.
    out = apply_levels(df, {"MAJfirstcode": 2})
    assert "MAJfirstcode" not in out.columns
    assert "MAJfirst" not in out.columns
    assert "MAJfirstcol" not in out.columns


# ---------------------------------------------------------------------------
# 1.2 Plant span integrity
# ---------------------------------------------------------------------------
@FAST
@given(n=st.integers(min_value=10, max_value=60), seed=st.integers(0, 10_000))
def test_plant_span_integrity(n, seed):
    df = pd.DataFrame({"row_id": np.arange(n), "Class": ["FY"] * n})
    planted, truth = plant_identifiers(df, seed=seed)
    comment_by_row = planted.set_index("row_id")["comment"].to_dict()
    for t in truth.itertuples():
        comment = comment_by_row[t.row_id]
        assert comment[t.start:t.end] == t.value, (
            f"span mismatch row {t.row_id}: {comment[t.start:t.end]!r} != {t.value!r}")
